def _seed_and_backfill() -> None:
    import uuid
    from datetime import datetime, timezone

    from packages.domain.capabilities import CAPABILITIES, DEFAULT_ROLE_TEMPLATES

    bind = op.get_bind()

    # 1. Capabilities: the global, static reference table.
    for cap in CAPABILITIES:
        bind.execute(
            sa.text("INSERT INTO capabilities (key, description) VALUES (:key, :description)"),
            {"key": cap.key, "description": cap.description},
        )

    # 2. Role templates + bundles: seeded once per EXISTING organization.
    org_ids = [row[0] for row in bind.execute(sa.text("SELECT id FROM organizations"))]
    now = datetime.now(timezone.utc)
    role_template_id_by_org_and_key: dict[tuple[str, str], str] = {}
    for org_id in org_ids:
        for key, capability_keys in DEFAULT_ROLE_TEMPLATES.items():
            template_id = str(uuid.uuid4())
            role_template_id_by_org_and_key[(org_id, key)] = template_id
            bind.execute(
                sa.text(
                    "INSERT INTO role_templates (id, organization_id, key, name, is_system, created_at) "
                    "VALUES (:id, :org_id, :key, :name, true, :now)"
                ),
                {"id": template_id, "org_id": org_id, "key": key, "name": key.replace("_", " ").title(), "now": now},
            )
            for capability_key in capability_keys:
                bind.execute(
                    sa.text(
                        "INSERT INTO role_template_capabilities (role_template_id, capability_key) "
                        "VALUES (:template_id, :capability_key)"
                    ),
                    {"template_id": template_id, "capability_key": capability_key},
                )

    # 3. Memberships: one row per existing user. 'creator' (the column default, meaning
    # no role was ever explicitly set) maps to the least-privileged 'member'; any other
    # existing value -- in practice only 'director', used by the dev-login bootstrap user
    # and every test tenant -- maps to 'owner', since those are exactly the users who
    # currently rely on unrestricted access.
    users = list(bind.execute(sa.text("SELECT id, organization_id, role FROM users")))
    for user_id, organization_id, role in users:
        org_role = "member" if role == "creator" else "owner"
        bind.execute(
            sa.text(
                "INSERT INTO memberships (id, user_id, organization_id, org_role, status, created_at) "
                "VALUES (:id, :user_id, :org_id, :org_role, 'active', :now)"
            ),
            {"id": str(uuid.uuid4()), "user_id": user_id, "org_id": organization_id, "org_role": org_role, "now": now},
        )

    # 4. Project memberships: every (existing user, existing project) pair in the SAME
    # organization, on the 'director' template (ADR-003 section 3 step 2). This is the
    # safety net for any 'member'-role user above; for 'owner'-role users it is inert
    # (AuthzService never consults project_memberships for an org owner) but kept for
    # consistency with the ADR and in case an owner is later demoted.
    projects = list(bind.execute(sa.text("SELECT id, organization_id FROM projects")))
    users_by_org: dict[str, list[str]] = {}
    for user_id, organization_id, _role in users:
        users_by_org.setdefault(organization_id, []).append(user_id)
    for project_id, organization_id in projects:
        director_template_id = role_template_id_by_org_and_key.get((organization_id, "director"))
        if director_template_id is None:
            continue  # an org with no users seeded no templates; nothing to backfill
        for user_id in users_by_org.get(organization_id, []):
            bind.execute(
                sa.text(
                    "INSERT INTO project_memberships (id, user_id, project_id, role_template_id, created_at) "
                    "VALUES (:id, :user_id, :project_id, :template_id, :now)"
                ),
                {
                    "id": str(uuid.uuid4()),
                    "user_id": user_id,
                    "project_id": project_id,
                    "template_id": director_template_id,
                    "now": now,
                },
            )


